function CommonSwitch.init()
	local ok, guideTypeData = pcall(require, "Common.Data.event_common_guide_type_data")

	if ok then
		for _, typeName in pairs(guideTypeData) do
			local key = "ACT_TYPE_" .. typeName

			if CommonSwitch[key] == nil then
				CommonSwitch[key] = true
			end
		end
	end
end

return CommonSwitch
